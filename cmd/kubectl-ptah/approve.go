func stdinIsTerminal() bool {
	return term.IsTerminal(int(os.Stdin.Fd()))
}

// connector opens the cluster for a command. Tests replace it.
var connector = connect

func approveCommand(ctx context.Context, arguments []string, stdin io.Reader, interactive bool, stdout, stderr io.Writer) int {
	flags := pflag.NewFlagSet("kubectl ptah approve", pflag.ContinueOnError)
	flags.SetOutput(stderr)
	flags.Usage = func() { usage(stderr) }

	var (
		fingerprint = flags.String("plan-fingerprint", "", "approve without asking, only if the current plan carries this fingerprint; "+
			"like an answer on a terminal, it waits up to "+statusview.Duration(gateTimeout)+" for an interval read of the operator to end before it sends")
		name        = flags.String("name", "", "name of the approval (default: generated by the API server from the resource's name, for a printed approval too)")
		dryRun      = flags.String("dry-run", "none", "none, client (print the approval; send nothing) or server (admission checks it; nothing is stored)")
		output      = flags.StringP("output", "o", "text", "text, yaml or json")
		namespace   = flags.StringP("namespace", "n", "", "namespace of the resource (default: the kubeconfig context's)")
		kubeconfig  = flags.String("kubeconfig", "", "path to a kubeconfig file (default: KUBECONFIG, then ~/.kube/config)")
		kubeContext = flags.String("context", "", "kubeconfig context to use (default: the current one)")
		timeout     = flags.Duration("timeout", 30*time.Second, "how long each request to the API server may take; the wait for an "+
			"interval read of the operator is bounded by "+statusview.Duration(gateTimeout)+", not by this")
		wait        = flags.Bool("wait", false, "once the approval is stored, wait until the operator has applied the plan and read the database afterwards")
		waitTimeout = flags.Duration("wait-timeout", defaultWaitTimeout, "how long --wait waits")
	)
	if err := flags.Parse(arguments); err != nil {
		if errors.Is(err, pflag.ErrHelp) {
			return exitOK
		}
		fmt.Fprintf(stderr, "kubectl-ptah: %v\n", err)
		return exitUsage
	}
	if flags.NArg() != 1 {
		fmt.Fprintf(stderr, "kubectl-ptah: name one resource, as schema/NAME or migration/NAME\n\n")
		usage(stderr)
		return exitUsage
	}
	family, resource, err := approve.ParseTarget(flags.Arg(0))
	if err != nil {
		fmt.Fprintf(stderr, "kubectl-ptah: %v\n", err)
		return exitUsage
	}
	switch *dryRun {
	case "none", "client", "server":
	default:
		fmt.Fprintf(stderr, "kubectl-ptah: --dry-run is none, client or server, not %q\n", *dryRun)
		return exitUsage
	}
	switch {
	case *wait && *dryRun != "none":
		fmt.Fprintf(stderr, "kubectl-ptah: --wait waits for the Apply an approval allows, and a dry run stores no approval\n")
		return exitUsage
	case *wait && *waitTimeout <= 0:
		fmt.Fprintf(stderr, "kubectl-ptah: --wait-timeout has to be longer than zero, not %s\n", *waitTimeout)
		return exitUsage
	}
	switch *output {
	case "text", "yaml", "json":
	default:
		fmt.Fprintf(stderr, "kubectl-ptah: unknown output format %q; it is one of [text yaml json]\n", *output)
		return exitUsage
	}

	cluster, resolved, err := connector(*kubeconfig, *kubeContext, *namespace, *timeout)
	if err != nil {
		fmt.Fprintf(stderr, "kubectl-ptah: %v\n", err)
		return exitFailed
	}

	// --timeout bounds a conversation with the API server, never the person:
	// the read gets a deadline of its own here, and the create gets another
	// once the person has answered, however long the review took.
	loadCtx, cancelLoad := context.WithTimeout(ctx, *timeout)
	review, err := approve.Load(loadCtx, cluster, family, resolved, resource)
	cancelLoad()
	switch {
	case errors.Is(err, approve.ErrNotFound), errors.Is(err, approve.ErrNothingToApprove):
		fmt.Fprintf(stderr, "kubectl-ptah: %v\n", err)
		return exitAbsent
	case err != nil:
		fmt.Fprintf(stderr, "kubectl-ptah: %v\n", err)
		return exitFailed
	}
	if review.Missing {
		// The plan the status names is not stored: an approval in any mode
		// would bind an object nobody reviewed.
		fmt.Fprintf(stderr, "kubectl-ptah: %s Nothing was approved.\n", review.Closed)
		return exitNotDone
	}

	// Every mode, --dry-run client included, takes the same decision: the
	// fingerprint of the plan the caller reviewed, or a review here answered
	// with yes. A manifest is an approval waiting to be created.
	printOnly := *dryRun == "client"
	if *fingerprint != "" {
		if *fingerprint != review.Fingerprint {
			fmt.Fprintf(stderr, "kubectl-ptah: the current plan of %s/%s is %s with fingerprint %s, not the %s given. Nothing was approved; review the current plan.\n",
				family, resource, review.PlanName, statusview.Clean(review.Fingerprint), statusview.Clean(*fingerprint))
			return exitNotDone
		}
	} else if !interactive {
		fmt.Fprintf(stderr, "kubectl-ptah: approve asks for a decision on a terminal. Without one, pass --plan-fingerprint with the fingerprint of the plan you reviewed (kubectl ptah plan %s shows it).\n", resource)
		return exitUsage
	}
	if !review.Open {
		switch {
		case printOnly:
			// A manifest outlives the moment: the operator reading again at its
			// interval closes the gate for a while, and the plan stays current.
			fmt.Fprintf(stderr, "kubectl-ptah: %s Admission would refuse this approval now.\n", review.Closed)
		case review.Reading:
			// The read ends at the gate again by itself. The decision is taken
			// now, about this plan, and sent once the gate is open with it.
			fmt.Fprintf(stderr, "kubectl-ptah: %s A decision taken now is sent when that read ends, if this plan is still the one waiting.\n",
				review.Closed)
		default:
			fmt.Fprintf(stderr, "kubectl-ptah: %s Nothing was approved.\n", review.Closed)
			return exitNotDone
		}
	}
	if *fingerprint == "" {
		// stdout carries the object whenever one is printed, so the review
		// goes beside the prompt instead.
		reviewOut := stdout
		if printOnly || *output != "text" {
			reviewOut = stderr
		}
		if err := approve.RenderReview(reviewOut, review); err != nil {
			fmt.Fprintf(stderr, "kubectl-ptah: write the plan: %v\n", err)
			return exitFailed
		}
		question := "Approve plan %s of %s/%s in %s? Type yes to approve: "
		switch *dryRun {
		case "client":
			question = "Print the approval of plan %s of %s/%s in %s? Type yes to print it: "
		case "server":
			question = "Ask admission about an approval of plan %s of %s/%s in %s, storing nothing? Type yes to ask: "
		}
		fmt.Fprintf(stderr, "\n"+question, review.PlanName, family, resource, resolved)
		answer, _ := bufio.NewReader(stdin).ReadString('\n')
		if strings.TrimSpace(answer) != "yes" {
			fmt.Fprintln(stderr, "Nothing was approved.")
			return exitNotDone
		}
	}

	if printOnly {
		// The manifest for a declarative workflow: the decision and nothing
		// else. Admission stamps the approver from whoever creates it. Nothing
		// is sent.
		format := *output
		if format == "text" {
			format = "yaml"
		}
		if code := printObject(stdout, stderr, approve.Manifest(review, *name), format); code != exitOK {
			return code
		}
		// stdout is the manifest alone, for a redirect; who creates it is
		// said beside it.
		fmt.Fprintln(stderr, printedApprover)
		return exitOK
	}

	submitCtx, cancelSubmit := context.WithTimeout(ctx, *timeout)
	defer cancelSubmit()
	target := operate.Ref{Family: operate.Family(family), Namespace: resolved, Name: resource}
	var baseline client.Object
	if *wait {
		// The resource before the approval exists is the wait's baseline: no
		// Apply it records can be one this approval allowed.
		if baseline, err = readResource(submitCtx, cluster, target); err != nil {
			fmt.Fprintf(stderr, "kubectl-ptah: %v\nNothing was approved.\n", err)
			return exitFailed
		}
	}
	// The operator reads a waiting resource again at its interval, which
	// closes the gate until the read ends; a person who took longer than the
	// interval over the plan meets it. Submit waits for the gate then, and
	// each request it sends carries --timeout of its own.
	result := approve.Submit(ctx, cluster, review, approve.Options{
		Name: *name, ServerDryRun: *dryRun == "server", Await: gateTimeout, CallTimeout: *timeout,
		// A progress line, as a wait's own: what Submit found is said once,
		// before the prompt when it was there to see then.
		Waiting: func(string) {
			fmt.Fprintf(stderr, "Waiting up to %s for the operator to end its read of %s/%s. If plan %s is back at the "+
				"approval gate then, the approval goes to admission.\n", statusview.Duration(gateTimeout), family, resource, review.PlanName)
		},
	})
	switch result.Outcome {
	case approve.Admitted, approve.Previewed:
		if *output != "text" {
			if code := printObject(stdout, stderr, result.Approval, *output); code != exitOK || !*wait {
				return code
			}
			return waitForApply(ctx, cluster, target, review, result.Approval, baseline, *waitTimeout, false, stdout, stderr)
		}
		approver, at := result.Approver()
		verb := "Approved"
		if result.Outcome == approve.Previewed {
			verb = "Admission accepts this approval; nothing was stored (server dry run). It would be"
		}
		when := ""
		if at != nil && !at.IsZero() {
			when = " at " + at.UTC().Format(time.RFC3339)
		}
		fmt.Fprintf(stdout, "%s: %s %s/%s, recorded by admission as %s%s.\nIt binds plan %s, fingerprint %s.\n",
			verb, family.ApprovalKind(), resolved, result.Approval.GetName(), statusview.Clean(approver), when,
			review.PlanName, statusview.Clean(review.Fingerprint))
		if *wait {
			return waitForApply(ctx, cluster, target, review, result.Approval, baseline, *waitTimeout, true, stdout, stderr)
		}
		if result.Outcome == approve.Admitted {
			fmt.Fprintf(stdout, "The operator runs it under the resource's policy; kubectl ptah %s %s -n %s shows how far it got.\n", family, resource, resolved)
		}
		return exitOK
	case approve.Changed, approve.Closed:
		fmt.Fprintf(stderr, "kubectl-ptah: %s\n", result.Message)
		return exitNotDone
	case approve.Forbidden, approve.Refused:
		fmt.Fprintf(stderr, "kubectl-ptah: %s\n", result.Message)
		return exitRefused
	case approve.Unknown:
		fmt.Fprintf(stderr, "kubectl-ptah: %s\n", result.Message)
		return exitUnknown
	default:
		fmt.Fprintf(stderr, "kubectl-ptah: %s\n", result.Message)
		return exitFailed
	}
}

// printedApprover is what a printed approval leaves to whoever creates it.
// Admission stamps the approver from the identity that creates the object,
// so a GitOps controller that applies it from a repository is recorded in
// place of the person who reviewed the plan.
const printedApprover = "Create this approval as the person who decided: admission records whoever creates it as the approver, " +
	"a GitOps controller that applies it included."

// gateTimeout is how long approve waits, once the person has decided, for
// the operator to end a read of the resource and be back at the approval
// gate. A read takes a few Jobs; one that takes longer than this is not the
// interval's read.
const gateTimeout = 5 * time.Minute

// printObject writes an object as YAML or JSON, the way kubectl prints one.
func printObject(stdout, stderr io.Writer, object client.Object, format string) int {
	kind := object.GetObjectKind().GroupVersionKind().Kind
	object.SetManagedFields(nil)
	var (
		data []byte
		err  error
	)
	if format == "json" {
		data, err = json.MarshalIndent(object, "", "  ")
		data = append(data, '\n')
	} else {
		data, err = yaml.Marshal(object)
	}
	if err != nil {
		fmt.Fprintf(stderr, "kubectl-ptah: encode the %s: %v\n", kind, err)
		return exitFailed
	}
	if _, err := stdout.Write(data); err != nil {
		fmt.Fprintf(stderr, "kubectl-ptah: write the %s: %v\n", kind, err)
		return exitFailed
	}
	return exitOK
}

// waitForApply waits for the operator to apply the plan an approval was
// stored for, and to read the database afterwards. For a schema only that
// plan counts. For a migration only the run that carried out that plan under
// this approval counts, since a run records both.
func waitForApply(ctx context.Context, reader client.Reader, ref operate.Ref, review approve.Review, approval, baseline client.Object,
	timeout time.Duration, text bool, stdout, stderr io.Writer) int {
	options := operate.WaitOptions{Target: operate.TargetApplied, Timeout: timeout, Since: baseline}
	if ref.Family == operate.FamilySchema {
		options.Plan = review.PlanName
	} else {
		options.Decision = &operate.Decision{
			PlanName: review.PlanName, PlanUID: review.PlanUID, PlanFingerprint: review.Fingerprint,
			ApprovalName: approval.GetName(), ApprovalUID: approval.GetUID(),
		}
	}
	result, code := waitFor(ctx, reader, ref, options, text, stderr)
	if code == exitOK && text {
		writeReached(stdout, result)
	}
	return code
}
